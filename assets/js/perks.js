const BY_FILE = Object.fromEntries(PERKS.map((p) => [p.file, p]));

export const perkByFile = (file) => BY_FILE[file] ?? null;
export const perkName = (file) => BY_FILE[file]?.name ?? file.replace(/\.png$/, '');

/** Anzeigename des Besitzers, oder null bei allgemeinen Perks. */
export function perkOwnerLabel(perk) {
  if (!perk || perk.general) return null;
  if (!perk.owner) return 'unbekannt';
  return KILLER_LABELS[perk.owner] ?? SURVIVOR_LABELS[perk.owner]
    ?? EXTRA_OWNER_LABELS[perk.owner] ?? perk.owner;
}
